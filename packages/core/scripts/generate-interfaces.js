#!/usr/bin/env node

/**
 * Script to automatically generate interfaces.ts barrel file
 * Scans all component directories and exports their interfaces
 */

const fs = require('fs');
const path = require('path');

const COMPONENTS_DIR = path.join(__dirname, '../src/components');
const GLOBAL_DIR = path.join(__dirname, '../src/global');
const OUTPUT_FILE = path.join(__dirname, '../src/interfaces.ts');

// Files that contain interfaces/types
const INTERFACE_FILES = new Set(['interfaces.ts', 'types.ts']);

const INTERFACE_REGEX = /export\s+interface\s+(\w+)/g;
const TYPE_REGEX = /export\s+type\s+(\w+)\s*=/g;

/**
 * Find all interface/type files in a directory recursively
 */
function findInterfaceFiles(dir, basePath = '') {
  const results = [];

  if (!fs.existsSync(dir)) return results;

  // Use withFileTypes for better performance (no need for separate stat calls)
  const items = fs.readdirSync(dir, { withFileTypes: true });

  for (const item of items) {
    const fullPath = path.join(dir, item.name);

    if (item.isDirectory()) {
      results.push(...findInterfaceFiles(fullPath, path.join(basePath, item.name)));
    } else if (INTERFACE_FILES.has(item.name)) {
      results.push({
        file: item.name,
        dir: basePath,
        relativePath: path.join(basePath, item.name).replaceAll('\\', '/'),
      });
    }
  }

  return results;
}

/**
 * Extract exported types from a file
 */
function extractExports(filePath) {
  const content = fs.readFileSync(filePath, 'utf-8');
  const exports = [];

  // Use pre-compiled regex patterns
  for (const match of content.matchAll(INTERFACE_REGEX)) {
    exports.push(match[1]);
  }

  for (const match of content.matchAll(TYPE_REGEX)) {
    exports.push(match[1]);
  }

  return exports;
}

/**
 * Generate global interfaces section
 */
function generateGlobalSection() {
  const lines = [];

  // Add global interfaces
  const globalInterfacesDir = path.join(GLOBAL_DIR, 'interfaces');
  if (fs.existsSync(globalInterfacesDir)) {
    const globalFiles = fs.readdirSync(globalInterfacesDir).filter(f => f.endsWith('.ts') && f !== 'index.ts');

    for (const file of globalFiles) {
      const filePath = path.join(globalInterfacesDir, file);
      const exports = extractExports(filePath);
      if (exports.length > 0) {
        const importPath = `./global/interfaces/${file.replace('.ts', '')}`;
        lines.push(`export type { ${exports.join(', ')} } from '${importPath}';`);
      }
    }
  }

  // Add global types
  const globalTypesFile = path.join(GLOBAL_DIR, 'types.ts');
  if (fs.existsSync(globalTypesFile)) {
    const exports = extractExports(globalTypesFile);
    if (exports.length > 0) {
      lines.push(`export type { ${exports.join(', ')} } from './global/types';`);
    }
  }

  return lines.join('\n');
}

/**
 * Generate component interfaces section
 */
function generateComponentSection() {
  const lines = [];
  const componentFiles = findInterfaceFiles(COMPONENTS_DIR, 'components');

  // Group by component
  const byComponent = {};
  for (const fileInfo of componentFiles) {
    const componentName = fileInfo.dir.split(path.sep)[1];
    if (!byComponent[componentName]) {
      byComponent[componentName] = [];
    }
    byComponent[componentName].push(fileInfo);
  }

  // Sort components alphabetically
  const sortedComponents = Object.keys(byComponent).sort();

  for (const componentName of sortedComponents) {
    lines.push('', `// ${componentName}`);

    const files = byComponent[componentName];
    for (const fileInfo of files) {
      const fullPath = path.join(COMPONENTS_DIR, fileInfo.relativePath.replace('components/', ''));
      const exports = extractExports(fullPath);

      if (exports.length > 0) {
        const importPath = `./${fileInfo.relativePath.replace('.ts', '')}`;
        lines.push(`export type { ${exports.join(', ')} } from '${importPath}';`);
      }
    }
  }

  return lines.join('\n');
}

/**
 * Generate the interfaces.ts content
 */
function generateInterfacesFile() {
  const lines = [
    '/**',
    ' * @fileoverview Auto-generated barrel file for all component interfaces',
    ' * ',
    ' * This file is automatically generated by scripts/generate-interfaces.js',
    " * Do not edit manually - run 'pnpm run generate:interfaces' to update",
    ' */',
    '',
    '// ============================================================================',
    '// Global Interfaces and Types',
    '// ============================================================================',
    generateGlobalSection(),
    '',
    '// ============================================================================',
    '// Component Interfaces and Types',
    '// ============================================================================',
    generateComponentSection(),
  ];

  return lines.join('\n');
}

// Generate and write the file
try {
  console.log('🔍 Scanning for interfaces...');
  const content = generateInterfacesFile();

  fs.writeFileSync(OUTPUT_FILE, content, 'utf-8');
  console.log('✅ Generated interfaces.ts successfully!');
  console.log(`📝 File: ${OUTPUT_FILE}`);
} catch (error) {
  console.error('❌ Error generating interfaces.ts:', error);
  process.exit(1);
}
